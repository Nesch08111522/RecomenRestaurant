-- Flexible document storage used by the Flask models.
-- Apply this once in the Supabase SQL Editor before starting the app.
BEGIN;

CREATE TABLE IF NOT EXISTS public.app_records (
    collection TEXT NOT NULL CHECK (length(collection) BETWEEN 1 AND 80),
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    payload JSONB NOT NULL CHECK (jsonb_typeof(payload) = 'object'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (collection, id)
);

CREATE INDEX IF NOT EXISTS idx_app_records_payload
    ON public.app_records USING GIN (payload jsonb_path_ops);

-- The Flask server connects with its server-side PostgreSQL credential.
-- The table is not exposed to Supabase's browser-facing API roles.
ALTER TABLE public.app_records ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.app_records FROM anon, authenticated;

COMMIT;
