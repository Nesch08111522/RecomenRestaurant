BEGIN;

CREATE TABLE IF NOT EXISTS public.sr_businesses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug TEXT NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
    name TEXT NOT NULL CHECK (length(trim(name)) BETWEEN 2 AND 160),
    status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','pending_review','active','suspended','archived')),
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(metadata) = 'object'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.sr_branches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL REFERENCES public.sr_businesses(id) ON DELETE CASCADE,
    name TEXT NOT NULL CHECK (length(trim(name)) BETWEEN 2 AND 120),
    address TEXT,
    district TEXT,
    latitude NUMERIC(9,6),
    longitude NUMERIC(9,6),
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('draft','active','inactive')),
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(metadata) = 'object'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (business_id, name)
);

CREATE TABLE IF NOT EXISTS public.sr_memberships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    business_id BIGINT NOT NULL REFERENCES public.sr_businesses(id) ON DELETE CASCADE,
    role TEXT NOT NULL CHECK (role IN ('business_owner','business_admin','manager','cashier','waiter','kitchen')),
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('invited','active','revoked')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, business_id)
);

CREATE TABLE IF NOT EXISTS public.sr_settings (
    business_id BIGINT NOT NULL REFERENCES public.sr_businesses(id) ON DELETE CASCADE,
    key TEXT NOT NULL CHECK (length(trim(key)) BETWEEN 1 AND 80),
    value JSONB NOT NULL CHECK (jsonb_typeof(value) IN ('object','array','string','number','boolean','null')),
    updated_by BIGINT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (business_id, key)
);

CREATE TABLE IF NOT EXISTS public.sr_audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT,
    business_id BIGINT REFERENCES public.sr_businesses(id) ON DELETE SET NULL,
    action TEXT NOT NULL CHECK (length(trim(action)) BETWEEN 2 AND 120),
    resource_type TEXT NOT NULL CHECK (length(trim(resource_type)) BETWEEN 2 AND 80),
    resource_id TEXT,
    request_id UUID,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(metadata) = 'object'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_sr_branches_business ON public.sr_branches (business_id);
CREATE INDEX IF NOT EXISTS idx_sr_memberships_user ON public.sr_memberships (user_id, status);
CREATE INDEX IF NOT EXISTS idx_sr_memberships_business ON public.sr_memberships (business_id, status);
CREATE INDEX IF NOT EXISTS idx_sr_audit_business_time ON public.sr_audit_events (business_id, created_at DESC);

ALTER TABLE public.sr_businesses ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sr_branches ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sr_memberships ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sr_settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sr_audit_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.sr_businesses, public.sr_branches, public.sr_memberships, public.sr_settings, public.sr_audit_events FROM anon, authenticated;

COMMIT;
