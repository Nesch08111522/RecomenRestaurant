-- SmartResto PostgreSQL schema
-- Compatible con PostgreSQL 14+. No requiere PostGIS en esta primera migración.
-- Las columnas legacy_* y source_snapshot conservan trazabilidad sin esconder
-- relaciones de negocio en JSON.

BEGIN;

CREATE TABLE IF NOT EXISTS roles (
    code VARCHAR(32) PRIMARY KEY,
    description VARCHAR(160) NOT NULL
);

INSERT INTO roles (code, description) VALUES
    ('user', 'Usuario final'),
    ('business_owner', 'Empresario con uno o varios restaurantes'),
    ('admin', 'Administrador de la plataforma')
ON CONFLICT (code) DO NOTHING;

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(80) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role_code VARCHAR(32) NOT NULL REFERENCES roles(code),
    status VARCHAR(24) NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'SUSPENDED', 'PENDING', 'DELETED')),
    email VARCHAR(255),
    display_name VARCHAR(160),
    preferences JSONB NOT NULL DEFAULT '{}'::jsonb,
    legacy_source_file TEXT,
    legacy_source_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (legacy_source_file, legacy_source_id),
    UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS businesses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE RESTRICT,
    legal_name VARCHAR(200),
    tax_identifier VARCHAR(80),
    registration_data JSONB NOT NULL DEFAULT '{}'::jsonb,
    status VARCHAR(24) NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'SUSPENDED', 'PENDING')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL UNIQUE,
    slug VARCHAR(140) UNIQUE,
    icon TEXT,
    image_url TEXT,
    legacy_source_file TEXT,
    legacy_source_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS restaurants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT REFERENCES businesses(id) ON DELETE RESTRICT,
    category_id BIGINT REFERENCES categories(id) ON DELETE RESTRICT,
    name VARCHAR(180) NOT NULL,
    slug VARCHAR(220),
    description TEXT NOT NULL DEFAULT '',
    address TEXT NOT NULL DEFAULT '',
    district VARCHAR(120) NOT NULL DEFAULT '',
    phone VARCHAR(60),
    image TEXT,
    tags JSONB NOT NULL DEFAULT '[]'::jsonb,
    features JSONB NOT NULL DEFAULT '[]'::jsonb,
    dietary_restrictions JSONB NOT NULL DEFAULT '[]'::jsonb,
    avg_price NUMERIC(12,2) CHECK (avg_price IS NULL OR avg_price >= 0),
    rating NUMERIC(3,2) NOT NULL DEFAULT 0 CHECK (rating >= 0 AND rating <= 5),
    review_count INTEGER NOT NULL DEFAULT 0 CHECK (review_count >= 0),
    open_time TIME,
    close_time TIME,
    promo TEXT,
    availability_status VARCHAR(24) NOT NULL DEFAULT 'UNKNOWN'
        CHECK (availability_status IN ('AVAILABLE', 'UNAVAILABLE', 'UNKNOWN')),
    approval_status VARCHAR(32) NOT NULL DEFAULT 'PENDIENTE_REVISION'
        CHECK (approval_status IN ('APROBADO_AUTOMATICAMENTE', 'PENDIENTE_REVISION', 'RECHAZADO', 'SUSPENDIDO')),
    publication_status VARCHAR(24) NOT NULL DEFAULT 'DRAFT'
        CHECK (publication_status IN ('DRAFT', 'PUBLISHED', 'UNPUBLISHED')),
    approval_source VARCHAR(40) NOT NULL DEFAULT 'LEGACY_IMPORT'
        CHECK (approval_source IN ('AI_PRECHECK', 'ADMIN_REVIEW', 'LEGACY_IMPORT', 'SYSTEM')),
    moderation_notes TEXT,
    legacy_verified BOOLEAN,
    legacy_source_file TEXT,
    legacy_source_id BIGINT,
    source_snapshot JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    moderated_at TIMESTAMPTZ,
    UNIQUE (legacy_source_file, legacy_source_id)
);

CREATE TABLE IF NOT EXISTS restaurant_locations (
    restaurant_id BIGINT PRIMARY KEY REFERENCES restaurants(id) ON DELETE CASCADE,
    latitude NUMERIC(9,6) CHECK (latitude BETWEEN -90 AND 90),
    longitude NUMERIC(9,6) CHECK (longitude BETWEEN -180 AND 180),
    accuracy_meters NUMERIC(10,2) CHECK (accuracy_meters IS NULL OR accuracy_meters >= 0),
    source VARCHAR(32) NOT NULL DEFAULT 'LEGACY_IMPORT',
    geocode_status VARCHAR(24) NOT NULL DEFAULT 'UNVERIFIED'
        CHECK (geocode_status IN ('VERIFIED', 'UNVERIFIED', 'INVALID')),
    address TEXT,
    district VARCHAR(120),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS restaurant_hours (
    restaurant_id BIGINT NOT NULL REFERENCES restaurants(id) ON DELETE CASCADE,
    day_of_week SMALLINT NOT NULL CHECK (day_of_week BETWEEN 0 AND 6),
    opens_at TIME,
    closes_at TIME,
    is_closed BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (restaurant_id, day_of_week)
);

CREATE TABLE IF NOT EXISTS dishes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT NOT NULL REFERENCES restaurants(id) ON DELETE CASCADE,
    name VARCHAR(180) NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    category VARCHAR(100),
    price NUMERIC(12,2) NOT NULL CHECK (price >= 0),
    is_available BOOLEAN NOT NULL DEFAULT TRUE,
    is_recommended BOOLEAN NOT NULL DEFAULT FALSE,
    seasonal BOOLEAN NOT NULL DEFAULT FALSE,
    preparation_time_minutes INTEGER CHECK (preparation_time_minutes IS NULL OR preparation_time_minutes >= 0),
    spiciness SMALLINT CHECK (spiciness IS NULL OR spiciness BETWEEN 0 AND 5),
    dietary_info JSONB NOT NULL DEFAULT '[]'::jsonb,
    tags JSONB NOT NULL DEFAULT '[]'::jsonb,
    nutritional_info JSONB NOT NULL DEFAULT '{}'::jsonb,
    source_snapshot JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (restaurant_id, name)
);

CREATE TABLE IF NOT EXISTS ingredients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160) NOT NULL UNIQUE,
    allergens JSONB NOT NULL DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS recipes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT NOT NULL REFERENCES restaurants(id) ON DELETE CASCADE,
    dish_id BIGINT REFERENCES dishes(id) ON DELETE SET NULL,
    name VARCHAR(180) NOT NULL,
    instructions TEXT,
    servings NUMERIC(8,2) CHECK (servings IS NULL OR servings > 0),
    source_snapshot JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS recipe_ingredients (
    recipe_id BIGINT NOT NULL REFERENCES recipes(id) ON DELETE CASCADE,
    ingredient_id BIGINT NOT NULL REFERENCES ingredients(id) ON DELETE RESTRICT,
    quantity NUMERIC(12,3) CHECK (quantity IS NULL OR quantity >= 0),
    unit VARCHAR(40),
    PRIMARY KEY (recipe_id, ingredient_id)
);

CREATE TABLE IF NOT EXISTS dish_ingredients (
    dish_id BIGINT NOT NULL REFERENCES dishes(id) ON DELETE CASCADE,
    ingredient_id BIGINT NOT NULL REFERENCES ingredients(id) ON DELETE RESTRICT,
    quantity NUMERIC(12,3) CHECK (quantity IS NULL OR quantity >= 0),
    unit VARCHAR(40),
    source VARCHAR(32) NOT NULL DEFAULT 'LEGACY_IMPORT',
    PRIMARY KEY (dish_id, ingredient_id)
);

CREATE TABLE IF NOT EXISTS menus (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT NOT NULL REFERENCES restaurants(id) ON DELETE CASCADE,
    menu_date DATE,
    day_of_week VARCHAR(20),
    menu_type VARCHAR(80),
    price NUMERIC(12,2) CHECK (price IS NULL OR price >= 0),
    specials JSONB NOT NULL DEFAULT '[]'::jsonb,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    source_snapshot JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (restaurant_id, menu_date)
);

CREATE TABLE IF NOT EXISTS menu_dishes (
    menu_id BIGINT NOT NULL REFERENCES menus(id) ON DELETE CASCADE,
    dish_id BIGINT NOT NULL REFERENCES dishes(id) ON DELETE RESTRICT,
    display_order INTEGER NOT NULL DEFAULT 0 CHECK (display_order >= 0),
    PRIMARY KEY (menu_id, dish_id)
);

CREATE TABLE IF NOT EXISTS user_preferences (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    preference_type VARCHAR(40) NOT NULL,
    value VARCHAR(160) NOT NULL,
    source VARCHAR(32) NOT NULL DEFAULT 'USER',
    weight NUMERIC(6,3) CHECK (weight IS NULL OR weight >= 0),
    PRIMARY KEY (user_id, preference_type, value)
);

CREATE TABLE IF NOT EXISTS interactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    restaurant_id BIGINT REFERENCES restaurants(id) ON DELETE SET NULL,
    dish_id BIGINT REFERENCES dishes(id) ON DELETE SET NULL,
    event_type VARCHAR(40) NOT NULL,
    context JSONB NOT NULL DEFAULT '{}'::jsonb,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS ratings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    restaurant_id BIGINT NOT NULL REFERENCES restaurants(id) ON DELETE CASCADE,
    rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, restaurant_id)
);

CREATE TABLE IF NOT EXISTS favorites (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    restaurant_id BIGINT NOT NULL REFERENCES restaurants(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, restaurant_id)
);

CREATE TABLE IF NOT EXISTS recommendations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    model_version VARCHAR(120) NOT NULL,
    strategy VARCHAR(40) NOT NULL,
    context JSONB NOT NULL DEFAULT '{}'::jsonb,
    generated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS recommendation_items (
    recommendation_id BIGINT NOT NULL REFERENCES recommendations(id) ON DELETE CASCADE,
    restaurant_id BIGINT REFERENCES restaurants(id) ON DELETE SET NULL,
    dish_id BIGINT REFERENCES dishes(id) ON DELETE SET NULL,
    rank INTEGER NOT NULL CHECK (rank > 0),
    score NUMERIC(12,6),
    reasons JSONB NOT NULL DEFAULT '[]'::jsonb,
    PRIMARY KEY (recommendation_id, rank),
    CHECK (restaurant_id IS NOT NULL OR dish_id IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS approvals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_type VARCHAR(40) NOT NULL,
    subject_id BIGINT NOT NULL,
    requested_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    final_status VARCHAR(32) NOT NULL
        CHECK (final_status IN ('APROBADO_AUTOMATICAMENTE', 'PENDIENTE_REVISION', 'RECHAZADO', 'SUSPENDIDO')),
    ai_verdict VARCHAR(32) CHECK (ai_verdict IS NULL OR ai_verdict IN ('APROBADO_AUTOMATICAMENTE', 'PENDIENTE_REVISION', 'RECHAZADO', 'SUSPENDIDO')),
    ai_confidence NUMERIC(6,5) CHECK (ai_confidence IS NULL OR (ai_confidence >= 0 AND ai_confidence <= 1)),
    ai_evaluation JSONB NOT NULL DEFAULT '{}'::jsonb,
    human_decision_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    reason TEXT,
    reversible BOOLEAN NOT NULL DEFAULT TRUE,
    source_snapshot JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS approval_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    approval_id BIGINT NOT NULL REFERENCES approvals(id) ON DELETE CASCADE,
    actor_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    previous_status VARCHAR(32),
    new_status VARCHAR(32) NOT NULL
        CHECK (new_status IN ('APROBADO_AUTOMATICAMENTE', 'PENDIENTE_REVISION', 'RECHAZADO', 'SUSPENDIDO')),
    event_type VARCHAR(40) NOT NULL,
    explanation TEXT,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS promotions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT NOT NULL REFERENCES restaurants(id) ON DELETE CASCADE,
    description TEXT NOT NULL,
    discount_percent NUMERIC(5,2) NOT NULL CHECK (discount_percent >= 0 AND discount_percent <= 100),
    valid_until DATE,
    source_snapshot JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title VARCHAR(180) NOT NULL,
    message TEXT NOT NULL,
    notification_type VARCHAR(40) NOT NULL,
    link TEXT,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    subject VARCHAR(180),
    status VARCHAR(24) NOT NULL DEFAULT 'OPEN'
        CHECK (status IN ('OPEN', 'CLOSED', 'MODERATED', 'SUSPENDED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS conversation_participants (
    conversation_id BIGINT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    joined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (conversation_id, user_id)
);

CREATE TABLE IF NOT EXISTS messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
    sender_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    body TEXT NOT NULL CHECK (length(trim(body)) > 0),
    moderation_status VARCHAR(24) NOT NULL DEFAULT 'PENDING'
        CHECK (moderation_status IN ('PENDING', 'APPROVED', 'BLOCKED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    read_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS migration_runs (
    run_id UUID PRIMARY KEY,
    source_manifest JSONB NOT NULL,
    status VARCHAR(24) NOT NULL CHECK (status IN ('STARTED', 'COMPLETED', 'FAILED')),
    row_counts JSONB NOT NULL DEFAULT '{}'::jsonb,
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ,
    error_message TEXT
);

CREATE TABLE IF NOT EXISTS audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    action VARCHAR(100) NOT NULL,
    resource_type VARCHAR(60),
    resource_id BIGINT,
    request_id VARCHAR(120),
    ip_hash VARCHAR(128),
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS bi_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    restaurant_id BIGINT REFERENCES restaurants(id) ON DELETE SET NULL,
    event_type VARCHAR(60) NOT NULL,
    event_value NUMERIC(14,4),
    dimensions JSONB NOT NULL DEFAULT '{}'::jsonb,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_restaurants_category_status ON restaurants(category_id, approval_status, publication_status);
CREATE INDEX IF NOT EXISTS idx_restaurants_business ON restaurants(business_id);
CREATE INDEX IF NOT EXISTS idx_restaurant_locations_lat_lng ON restaurant_locations(latitude, longitude);
CREATE INDEX IF NOT EXISTS idx_dishes_restaurant_available ON dishes(restaurant_id, is_available);
CREATE INDEX IF NOT EXISTS idx_menus_restaurant_date ON menus(restaurant_id, menu_date);
CREATE INDEX IF NOT EXISTS idx_promotions_restaurant_validity ON promotions(restaurant_id, valid_until);
CREATE INDEX IF NOT EXISTS idx_interactions_user_time ON interactions(user_id, occurred_at DESC);
CREATE INDEX IF NOT EXISTS idx_ratings_restaurant ON ratings(restaurant_id);
CREATE INDEX IF NOT EXISTS idx_approvals_subject ON approvals(subject_type, subject_id, created_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS uq_approval_legacy_import ON approval_events(approval_id, event_type) WHERE event_type = 'LEGACY_IMPORT';
CREATE INDEX IF NOT EXISTS idx_audit_events_actor_time ON audit_events(actor_user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_bi_events_restaurant_time ON bi_events(restaurant_id, occurred_at DESC);

COMMIT;
